#!/usr/bin/env python3
"""Build an entrapment library from an existing .oswpq bundle.

WHY. Every quality number in this project is currently relative to DIA-NN's ID list. The literature
pass established that (a) no published DIA-NN-vs-OpenSWATH precursor-yield comparison survived
adversarial verification, (b) one candidate pointed the OTHER way, and (c) per Wen et al. (Nat
Methods 2025) comparing ID counts at a fixed nominal FDR is not a sensitivity comparison at all
unless calibration is independently verified. So we cannot presently tell whether our 6,930 IDs are
6,930 real ones, or whether DIA-NN's 7,787 contains false positives we are correctly rejecting.

Entrapment breaks that circularity: sequences known a priori to be absent are searched alongside the
real targets. Any entrapment sequence reported at q<0.01 is a false positive by construction, so the
observed false discovery PROPORTION can be compared against the nominal q.

METHOD, and its limits. The honest way to build entrapment is to add peptides from a species absent
from the sample, with predicted spectra. That needs the PeptDeep models, which are not on this
cluster. This script uses the affordable approximation instead:

  promote a random fraction of the library's DECOYS to entrapment TARGETS, and drop them from the
  decoy set.

They carry real predicted spectra (they were generated by shuffling real targets), they are absent
from the sample by construction, and they are drawn from the same m/z and RT distributions as the
targets -- which the foreign-species approach does NOT guarantee.

What this approximation CANNOT tell you:
  * It shares the decoy generator's biases. If shuffled decoys are systematically easier or harder
    than real absent peptides, the FDP estimate inherits that.
  * Removing decoys shrinks the null, which itself perturbs q-value estimation. Keep the promoted
    fraction small (default 5%) so the remaining decoy set stays large.
  * It measures calibration of the TARGET-DECOY procedure against a decoy-derived truth. A foreign
    -species entrapment set would be a stronger test and should replace this once models are
    available.

usage: make_entrapment.py <in.oswpq> <out.oswpq> [fraction] [seed]
"""
import sys, os, zipfile, shutil, tempfile, hashlib

try:
    import pyarrow.parquet as pq, pyarrow as pa, pyarrow.compute as pc
except ImportError:
    sys.exit("needs pyarrow (use /scratch/kohlbach/mzpenv/bin/python)")

ENTRAP_PREFIX = "ENTRAP_"


def stable_pick(key: str, fraction: float, seed: int) -> bool:
    """Deterministic per-precursor selection. A hash, not an RNG: the same library must yield the
    same entrapment set on every machine and every run, or the FDP figures are not comparable."""
    h = hashlib.blake2b(f"{seed}:{key}".encode(), digest_size=8).digest()
    return (int.from_bytes(h, "big") % 1000000) < int(fraction * 1000000)


def main(src, dst, fraction=0.05, seed=1):
    work = tempfile.mkdtemp(prefix="entrap_")
    with zipfile.ZipFile(src) as z:
        z.extractall(work)

    pre_path = os.path.join(work, "library", "precursors.parquet")
    tra_path = os.path.join(work, "library", "transitions.parquet")
    pre = pq.read_table(pre_path)
    print(f"library: {pre.num_rows} precursor rows")

    decoy = pc.cast(pre["decoy"], "bool").to_pylist()
    traml = pre["traml_id"].to_pylist()
    pid = pre["precursor_id"].to_pylist()

    promoted, new_decoy, new_traml = set(), [], []
    for d, t, p in zip(decoy, traml, pid):
        if d and stable_pick(str(t), fraction, seed):
            promoted.add(p)
            new_decoy.append(False)                       # now a target...
            new_traml.append(ENTRAP_PREFIX + str(t))      # ...but a recognisable one
        else:
            new_decoy.append(d)
            new_traml.append(t)

    n_dec = sum(1 for d in decoy if d)
    print(f"decoys {n_dec} -> promoted {len(promoted)} to entrapment targets "
          f"({100.0*len(promoted)/max(1,n_dec):.1f}% of decoys), "
          f"{n_dec - len(promoted)} decoys remain")
    if len(promoted) == 0:
        sys.exit("no decoys promoted -- check the fraction and that the library HAS decoys")

    cols = {n: pre[n] for n in pre.schema.names}
    cols["decoy"] = pa.array(new_decoy, type=pre.schema.field("decoy").type)
    cols["traml_id"] = pa.array(new_traml, type=pre.schema.field("traml_id").type)
    pq.write_table(pa.table(cols, schema=pre.schema), pre_path)

    # Transitions carry their own decoy flag and must agree, or the prefilter's decoy pairing and
    # the scorer's label will disagree about the same precursor.
    tra = pq.read_table(tra_path)
    if "decoy" in tra.schema.names and "precursor_id" in tra.schema.names:
        tdec = pc.cast(tra["decoy"], "bool").to_pylist()
        tpid = tra["precursor_id"].to_pylist()
        tnew = [False if p in promoted else d for d, p in zip(tdec, tpid)]
        tcols = {n: tra[n] for n in tra.schema.names}
        tcols["decoy"] = pa.array(tnew, type=tra.schema.field("decoy").type)
        pq.write_table(pa.table(tcols, schema=tra.schema), tra_path)
        print(f"transitions: {sum(1 for a,b in zip(tdec,tnew) if a!=b)} rows relabelled")

    if os.path.exists(dst):
        os.remove(dst)
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_STORED) as z:
        for root, _, files in os.walk(work):
            for f in files:
                full = os.path.join(root, f)
                z.write(full, os.path.relpath(full, work))
    shutil.rmtree(work, ignore_errors=True)
    print(f"wrote {dst}")
    print(f"FDP check: count reported precursors whose traml_id starts with {ENTRAP_PREFIX!r};")
    print(f"           FDP = entrapment_hits / (entrapment_hits + target_hits) * "
          f"(1/{fraction:.3f} scaling for the sampled fraction)")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2],
         float(sys.argv[3]) if len(sys.argv) > 3 else 0.05,
         int(sys.argv[4]) if len(sys.argv) > 4 else 1)
